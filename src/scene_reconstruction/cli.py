from __future__ import annotations

import argparse
import importlib
from pathlib import Path


def parser():
    root = argparse.ArgumentParser(description="Aligned video geometry, depth and masks for Blender evaluation")
    sub = root.add_subparsers(dest="command", required=True)
    p = sub.add_parser("extract", help="Extract every frame and preserve source timestamps")
    p.add_argument("--video", type=Path, default=Path("data/IMG_1711.MOV"))
    p.add_argument("--output", type=Path, default=Path("data/frames"))
    p.add_argument("--color", choices=["auto", "tonemap", "sdr"], default="auto")
    p.add_argument("--ffmpeg", default="ffmpeg", help="Path to FFmpeg built with zscale and tonemap for HDR")
    p.set_defaults(module="frames", function="extract")
    for name, module, out in [("vggt", "vggt_omega", "vggt"), ("depth", "depth_anything3", "depth"), ("sam", "sam3_masks", "sam")]:
        p = sub.add_parser(name)
        p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
        p.add_argument("--output", type=Path, default=Path("outputs") / out)
        p.add_argument("--device", default="cuda")
        p.set_defaults(module=module, function="run")
        if name == "vggt":
            p.add_argument("--repo", type=Path, default=Path("vendor/vggt-omega"))
            p.add_argument("--checkpoint", type=Path, required=True)
            p.add_argument("--preset", choices=["quality", "quick"], default="quality",
                           help="quality: stride 2, cap 400, balanced 512; quick: stride 10, cap 72, max_size 512. Explicit flags override either preset")
            p.add_argument("--stride", type=int, help="Frame step; quality=2, quick=10")
            p.add_argument("--max-frames", type=int, help="Frame cap; quality=400, quick=72; 0 disables cap")
            p.add_argument("--precision", choices=["auto", "bf16", "fp16", "fp32"], help="Both presets use bf16")
            p.add_argument("--image-resolution", type=int, help="Both presets use 512; actual dimensions depend on mode/aspect")
            p.add_argument("--preprocess-mode", choices=["max_size", "balanced"], help="quality=balanced, quick=max_size")
            p.add_argument("--point-stride", type=int, help="Cloud export pixel step; quality=1, quick=4")
            p.add_argument("--max-points", type=int, help="Cloud export cap; quality=5000000, quick=1000000")
            p.add_argument("--confidence-percentile", type=float, help="Both presets use 50; filters only cloud export")
        elif name == "depth":
            p.add_argument("--model", default="depth-anything/DA3NESTED-GIANT-LARGE-1.1")
            p.add_argument("--model-revision")
            p.add_argument("--chunk-size", type=int, default=16)
            p.add_argument("--overlap", type=int, default=4)
            p.add_argument("--process-res", type=int, default=504)
            p.add_argument("--compression-level", type=int, choices=range(10), default=1,
                           help="Lossless NPZ storage: 0=uncompressed (larger files), 1=fast compression (default), 6=previous storage setting; does not change model predictions")
            p.add_argument("--stop-after-windows", type=int,
                           help="Profile at most this many windows in this invocation, including cache hits; rerun without this flag to complete the video")
        else:
            p.add_argument("--prompts", type=Path, default=Path("configs/objects.json"))
            p.add_argument("--checkpoint", type=Path)
            p.add_argument("--chunk-size", type=int, default=120)
            p.add_argument("--save-instances", action=argparse.BooleanOptionalAction, default=True)
            p.add_argument("--threshold", type=float, default=0.5)
    p = sub.add_parser("sam-dense", help="Independent point-grid discovery, video tracking and candidate reconciliation pilot")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--selection", type=Path, default=Path("configs/evaluation/1711_frames_100.json"))
    p.add_argument("--output", type=Path, default=Path("outputs/sam_dense_1711_2fps"))
    p.add_argument("--checkpoint", type=Path)
    gpu_selection = p.add_mutually_exclusive_group()
    gpu_selection.add_argument("--gpu-index", type=int, default=0, help="Single GPU: logical index inside CUDA_VISIBLE_DEVICES")
    gpu_selection.add_argument("--gpus", help="Parallel workers on comma-separated physical GPU IDs, e.g. 2,5,7; must be allowed by CUDA_VISIBLE_DEVICES if set")
    cadence = p.add_mutually_exclusive_group()
    cadence.add_argument("--discovery-fps", type=float, default=2.0,
                         help="Minimum discovery cadence; anchors at most 1/FPS seconds apart (default: 2)")
    cadence.add_argument("--anchor-count", type=int,
                         help="Override time-based discovery with a fixed count; intended for smoke tests")
    p.add_argument("--grid-side", type=int, default=32, help="Independent point prompts per side of each discovery image/crop")
    p.add_argument("--point-batch-size", type=int, default=16)
    p.add_argument("--crop-layers", type=int, choices=[0, 1], default=0, help="1 adds four overlapping magnified crops")
    p.add_argument("--min-mask-area", type=int, default=64)
    p.add_argument("--min-quality", type=float, default=.85)
    p.add_argument("--min-stability", type=float, default=.9)
    p.add_argument("--dedup-iou", type=float, default=.95)
    p.add_argument("--max-per-anchor", type=int, default=0, help="Optional tracking seed budget per discovery frame; default 0 tracks all accepted nonduplicate proposals. All quality-passing discovery masks are retained.")
    p.add_argument("--track-batch-size", type=int, default=8)
    p.add_argument("--frame-limit", type=int, default=0, help="Use only the first N selected frames for an API smoke test; 0 keeps all")
    p.add_argument("--stage", choices=["all", "discover", "track", "catalog"], default="all")
    p.add_argument("--resume", action="store_true", help="Reuse completed anchors/batches only with identical input hashes and settings")
    p.add_argument("--dry-run", action="store_true", help="Validate source data and print the plan without importing GPU models")
    p.set_defaults(module="sam3_dense", function="run")
    p = sub.add_parser("compare-masks", help="Strict, full-resolution per-frame IoU/Dice evaluation")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--predicted", type=Path, default=Path("outputs/sam/masks"))
    p.add_argument("--reference", type=Path, required=True, help="Blender binary masks: <object>/<frame:06d>.png")
    p.add_argument("--objects", nargs="+", required=True, help="Matching object directory names")
    p.add_argument("--output", type=Path, default=Path("outputs/comparison"))
    p.add_argument("--overlay-every", type=int, default=30, help="0 disables RGB/mask overlay PNGs")
    p.add_argument("--ignore-masks", type=Path, help="Optional frame PNGs of explicitly excluded pixels, e.g. hand occlusion")
    p.set_defaults(module="compare", function="run")
    p = sub.add_parser("measure", help="Estimate distance between source pixels using DA3 depth and intrinsics")
    p.add_argument("--depth-index", type=Path, default=Path("outputs/depth/index.json"))
    p.add_argument("--frame", type=int, required=True)
    p.add_argument("--pixels", nargs="+", required=True, help="Source pixel pairs, e.g. 400,800 700,1100")
    p.add_argument("--output", type=Path)
    p.set_defaults(module="measure", function="run")
    p = sub.add_parser("preview-depth", help="Create an RGB/depth video with one fixed color scale")
    p.add_argument("--depth-index", type=Path, default=Path("outputs/depth/index.json"))
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--output", type=Path, default=Path("outputs/depth_preview.mp4"))
    p.add_argument("--max-height", type=int, default=720)
    p.add_argument("--ffmpeg", default="ffmpeg")
    p.set_defaults(module="preview", function="run")
    p = sub.add_parser("select-evaluation-frames", help="Choose shared timestamps while retaining canonical source frame IDs")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--count", type=int, default=100)
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(module="evaluation_frames", function="run")
    p = sub.add_parser("render-entities", help="Render grouped Blender entity IDs and optional RGB at selected timestamps")
    p.add_argument("--blend", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--selection", type=Path, required=True)
    p.add_argument("--entities", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--samples", type=int, default=8)
    p.add_argument("--render-device", choices=["CPU", "METAL", "CUDA", "OPTIX"], default="CPU")
    p.add_argument("--resolution-scale", type=float, default=1.)
    p.add_argument("--rgb", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--frames", help="Optional selected source IDs for a smoke render")
    p.add_argument("--blender")
    p.set_defaults(module="blender_entities", function="run")
    p = sub.add_parser("prepare-entity-sam", help="Prepare one scene's sparse-frame SAM concept/instance run")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--selection", type=Path, required=True)
    p.add_argument("--entities", type=Path, required=True)
    p.add_argument("--render-index", type=Path)
    p.add_argument("--anchor-prompts", type=Path, help="Shared concept text/anchor policy for paired scene evaluation")
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(module="entity_sam", function="prepare")
    p = sub.add_parser("shared-entity-prompts", help="Choose common text/anchor inputs symmetrically across scene inventories")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--selection", type=Path, required=True)
    p.add_argument("--entities", type=Path, nargs="+", required=True)
    p.add_argument("--render-indices", type=Path, nargs="+", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(module="entity_sam", function="shared_prompts")
    p = sub.add_parser("export-entity-masks", help="Expand entity-ID rasters into binary masks for a SAM subset")
    p.add_argument("--render-index", type=Path, required=True)
    p.add_argument("--entities", type=Path, required=True)
    p.add_argument("--manifest", type=Path, required=True, help="Prepared sparse SAM frame manifest")
    p.add_argument("--objects", nargs="+", help="Optional explicit entity names; default all entities")
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(module="entity_artifacts", function="export_masks")
    p = sub.add_parser("preview-entities", help="Create original/RGB/entity-tint video and an entity legend")
    p.add_argument("--render-index", type=Path, required=True)
    p.add_argument("--entities", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--sam-masks", type=Path, help="Optional assembled physical-entity masks directory")
    p.add_argument("--sam-manifest", type=Path, help="Exact sparse manifest used for assembled SAM masks")
    p.add_argument("--max-height", type=int, default=480)
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(module="entity_artifacts", function="preview")
    p = sub.add_parser("review-entity-sam", help="Compare paired SAM concept unions with Blender categories; not physical-object scoring")
    p.add_argument("--root", type=Path, default=Path("."), help="IMG_1711 project root containing configs and outputs")
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--preview-height", type=int, default=480, help="Display preview height; metrics always use the full source pixel grid")
    p.set_defaults(module="entity_sam_review", function="run")
    p = sub.add_parser("catalog-instances", help="Summarize detected SAM tracks for physical-object mapping")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--sam-output", type=Path, default=Path("outputs/sam"))
    p.add_argument("--output", type=Path, default=Path("outputs/instance_catalog"))
    p.set_defaults(module="instances", function="catalog")
    p = sub.add_parser("assemble-instances", help="Build stable target masks from explicitly reviewed SAM track mappings")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--sam-output", type=Path, default=Path("outputs/sam"))
    p.add_argument("--mapping", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("outputs/assembled"))
    p.set_defaults(module="instances", function="run")
    p = sub.add_parser("blender-export", help="Export evaluated Blender cameras/mesh and optional camera-view depth/RGB")
    p.add_argument("--blend", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--blender", help="Blender executable; defaults to PATH or the macOS application")
    p.add_argument("--frames", default="all", help="Depth/RGB frame IDs, comma separated, or all; cameras always cover all frames")
    p.add_argument("--depth", action="store_true")
    p.add_argument("--rgb", action="store_true")
    p.add_argument("--resolution-scale", type=float, default=1.0)
    p.add_argument("--frame-start", type=float)
    p.add_argument("--time-scale", type=float, default=1.0)
    p.add_argument("--samples", type=int, default=16)
    p.add_argument("--camera")
    p.set_defaults(module="blender_export", function="run")
    p = sub.add_parser("align-vggt", help="Fit one global VGGT-to-Blender similarity and compare cameras")
    p.add_argument("--vggt", type=Path, default=Path("outputs/vggt"))
    p.add_argument("--blender-export", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--landmarks", type=Path)
    p.add_argument("--transform", type=Path)
    p.add_argument("--fit-frames", help="Comma-separated source frame IDs for fitting; other matched frames are held out")
    p.add_argument("--robust", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--robust-threshold", type=float)
    p.set_defaults(module="alignment", function="run")
    p = sub.add_parser("align-surfaces", help="Automatically align structural planes; cameras are evaluation only")
    p.add_argument("--vggt", type=Path, default=Path("outputs/vggt_quality"))
    p.add_argument("--blender-export", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--sample-points", type=int, default=300000, help="Point-cloud sample for plane detection; inference is unchanged")
    p.add_argument("--surface-profile", choices=["auto", "kitchen", "living_dining"], default="auto",
                   help="Named Blender surface profile; auto requires exactly one complete matching profile")
    p.add_argument("--voxel-size", type=float, help="Spatial balancing cell size in VGGT units; automatic by default")
    p.add_argument("--plane-threshold", type=float, help="RANSAC plane distance in VGGT units; automatic by default")
    p.add_argument("--max-planes", type=int, default=18)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--stability-runs", type=int, default=2, help="Independent detector seeds for a geometry-only stability check (default: 2)")
    p.add_argument("--viewer-points", type=int, default=5000000, help="Points in full 3D viewer; 0 skips viewer generation")
    p.set_defaults(module="surface_alignment", function="run")
    p = sub.add_parser("view-alignment", help="Build an offline interactive 3D scene/cloud/camera viewer")
    p.add_argument("--blender-export", type=Path, required=True)
    p.add_argument("--vggt", type=Path)
    p.add_argument("--alignment", type=Path)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--output", type=Path, required=True, help="Standalone .html file")
    p.add_argument("--max-points", type=int, default=5000000,
                   help="Maximum displayed cloud points (default: 5000000, all points in the quality export); lower for a lighter viewer")
    p.add_argument("--max-triangles", type=int, default=30000)
    p.add_argument("--max-images", type=int, default=72)
    p.set_defaults(module="alignment_viewer", function="run")
    p = sub.add_parser("compare-depth", help="Compare DA3 estimated depth against Blender camera-z renders")
    p.add_argument("--depth-index", type=Path, default=Path("outputs/depth/index.json"))
    p.add_argument("--blender-index", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--blender-unit-meters", type=float)
    p.add_argument("--scale-mode", choices=["metric", "global"], default="metric")
    p.add_argument("--fit-frames")
    p.add_argument("--max-depth", type=float)
    p.add_argument("--confidence-percentile", type=float, default=0)
    p.add_argument("--preview-count", type=int, default=12)
    p.set_defaults(module="depth_compare", function="run")
    p = sub.add_parser("doctor", help="Check local inputs, tools, and optional CUDA environment")
    p.add_argument("--manifest", type=Path, default=Path("data/frames/manifest.json"))
    p.add_argument("--gpu", action="store_true")
    p.set_defaults(module="doctor", function="run")
    return root


def main(argv=None):
    args = parser().parse_args(argv)
    module = importlib.import_module(f"scene_reconstruction.{args.module}")
    getattr(module, args.function)(args)

